# A brand-new user tries to find things, counting taps; screenshots for review.
import re, sys
from playwright.sync_api import sync_playwright
B="http://localhost:3100"; O="find/"; res=[]
def ok(name, cond, detail=""): res.append((cond,name,detail)); print(("PASS " if cond else "FAIL ")+name, detail)
with sync_playwright() as p:
    b=p.chromium.launch(); c=b.new_context(viewport={"width":390,"height":844},locale="ko-KR",timezone_id="Asia/Seoul",is_mobile=True,has_touch=True)
    pg=c.new_page(); errs=[]; pg.on("pageerror",lambda e: errs.append(str(e))); pg.clock.install()
    pg.goto(B); pg.get_by_role("button",name="시작하기").click()
    pg.get_by_role("radio",name=re.compile("^서울")).click(); pg.get_by_role("button",name="다음").click()
    pg.get_by_role("radio",name=re.compile("^부산")).click(); pg.get_by_role("button",name="다음").click()
    pg.get_by_role("button",name="나중에 할게요").click(); pg.wait_for_timeout(800)
    nav=pg.get_by_role("navigation").last.inner_text()
    ok("tabs say what is inside", all(x in nav for x in ["홈","지도","집중","엽서함","설정"]), nav.replace("\n"," "))
    g=pg.get_by_role("region",name=re.compile("첫 여행 가이드"))
    ok("new user sees a first-trip guide at 0/3", g.is_visible() and "0/3" in g.inner_text())
    pg.screenshot(path=O+"1_home_new.png",full_page=True)
    # find: change destination from home
    pg.get_by_role("link",name="목적지 바꾸기").click(); pg.wait_for_url("**/map"); pg.wait_for_timeout(800)
    ok("'목적지 바꾸기' opens the city search on the map", pg.locator("#dest-search").is_visible())
    pg.locator("#dest-search").fill("ㄷㅋ"); pg.wait_for_timeout(300)
    r=pg.get_by_role("list",name="검색 결과").inner_text(); ok("search by initials finds 도쿄", "도쿄" in r, r.split("\n")[0])
    pg.locator("#dest-search").fill("프랑스"); pg.wait_for_timeout(300)
    r=pg.get_by_role("list",name="검색 결과").inner_text(); ok("search by country finds 파리", "파리" in r)
    pg.locator("#dest-search").fill("아틀란티스"); pg.wait_for_timeout(300)
    ok("no-match explains what is available", "50개 도시" in pg.get_by_role("list",name="검색 결과").inner_text())
    pg.screenshot(path=O+"2_map_search.png",full_page=True)
    pg.locator("#dest-search").fill("도쿄"); pg.wait_for_timeout(300)
    pg.get_by_role("list",name="검색 결과").get_by_role("button").first.click(); pg.wait_for_timeout(500)
    st=pg.evaluate("() => JSON.parse(localStorage.getItem('wandermin.v1'))")
    ok("rerouting mid-plan only changes the route (no surprise takeoff)", st["plan"]["stops"][-1]=="tokyo" and not st["active"], str(st["plan"]["stops"]))
    # first flight from home
    pg.goto(B); pg.get_by_role("button",name=re.compile("바로 시작")).click(); pg.wait_for_url("**/focus")
    pg.clock.run_for(3*60*60*1000); pg.wait_for_timeout(1500)
    d=pg.get_by_role("dialog")
    ok("first arrival says where postcards are kept", d.locator("[data-where-cards]").count()==1)
    pg.screenshot(path=O+"3_arrival.png")
    pg.keyboard.press("Escape"); pg.wait_for_timeout(500)
    pg.goto(B); pg.wait_for_timeout(800)
    g=pg.get_by_role("region",name=re.compile("첫 여행 가이드"))
    ok("guide ticks off steps from the record", g.count()==1 and "2/3" in g.inner_text(), g.inner_text().replace("\n"," ")[:80] if g.count() else "")
    pg.screenshot(path=O+"4_home_after.png",full_page=True)
    # postcards tab: postcards first, short list
    pg.get_by_role("navigation").last.get_by_role("link",name="엽서함").click(); pg.wait_for_url("**/journal"); pg.wait_for_timeout(900)
    first_h2=pg.locator("main h2").first.inner_text()
    ok("Postcards tab opens on the postcard collection", "엽서" in first_h2, first_h2)
    ghosts=pg.locator("main .ghost-card").count()
    ok("only the nearest unvisited cities are listed at first", ghosts<=7, str(ghosts))
    pg.get_by_role("button",name=re.compile("더 보기")).click(); pg.wait_for_timeout(400)
    ok("'더 보기' reveals every city", pg.locator("main .ghost-card").count()>=45)
    pg.screenshot(path=O+"5_postcards.png")
    # settings
    pg.get_by_role("navigation").last.get_by_role("link",name="설정").click(); pg.wait_for_url("**/profile")
    ok("settings tab is titled 설정 and has backup", pg.locator("h1").inner_text()=="설정" and pg.get_by_role("button",name="기록 파일로 저장하기").is_visible())
    ok("no page errors", not errs, "; ".join(errs))
    b.close()
print(f"{sum(1 for r in res if r[0])}/{len(res)} passed")
