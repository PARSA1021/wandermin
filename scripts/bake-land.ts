/**
 * Bake Natural Earth 1:110m land (public domain, via the world-atlas package) into one SVG path
 * in an equirectangular projection, so the app needs no map library or tiles at runtime.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import type { Topology, GeometryCollection } from "topojson-specification";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"), "utf8")) as Topology<{ land: GeometryCollection }>;
const land = feature(topo, topo.objects.land) as unknown as { features: { geometry: { type: string; coordinates: number[][][] | number[][][][] } }[] };

// Projection shared with the app (src/features/map/projection.ts): 2 units per degree, lat 84°N … 58°S.
const K = 2, LAT_TOP = 84, LAT_BOTTOM = -58;
const x = (lng: number) => (lng + 180) * K;
const y = (lat: number) => (LAT_TOP - lat) * K;
const r = (n: number) => Math.round(n * 2) / 2;

const rings: number[][][] = [];
for (const f of land.features) {
  const g = f.geometry;
  const polys = g.type === "Polygon" ? [g.coordinates as number[][][]] : (g.coordinates as number[][][][]);
  for (const poly of polys) for (const ring of poly) rings.push(ring);
}
let d = "";
for (const ring of rings) {
  if (ring.every(([, lat]) => lat! < LAT_BOTTOM)) continue; // Antarctica sits below the frame
  let prev = "";
  ring.forEach(([lng, lat], i) => {
    const pt = `${r(x(lng!))} ${r(y(Math.max(LAT_BOTTOM - 4, lat!)))}`;
    if (pt === prev) return;
    d += (i === 0 ? "M" : "L") + pt;
    prev = pt;
  });
  d += "Z";
}
writeFileSync("src/features/map/land.ts",
  `// Generated by scripts/bake-land.ts from Natural Earth 1:110m land (public domain) via world-atlas.\n` +
  `// Equirectangular, ${K} units per degree, latitude ${LAT_TOP}°N to ${-LAT_BOTTOM}°S.\nexport const LAND_PATH = ${JSON.stringify(d)};\n`);
console.log(`land path: ${rings.length} rings, ${(d.length / 1024).toFixed(1)} KB`);
